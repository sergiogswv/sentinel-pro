/// Test scenario: Custom rules in a project
#[test]
fn test_capa3_custom_rules_loading() {
    let temp_dir = TempDir::new().expect("Failed to create temp dir");
    let project_path = temp_dir.path();

    // Create custom rules
    let rules_dir = project_path.join(".sentinel").join("custom-rules");
    fs::create_dir_all(&rules_dir).expect("Failed to create rules directory");

    let rule1 = r#"type: pattern
name: "No Debugger"
pattern: "debugger"
file_patterns: ["**/*.ts"]
severity: error
message: "Debugger statement not allowed"
enabled: true
"#;

    let rule2 = r#"type: pattern
name: "No Console"
pattern: "console\\.log"
file_patterns: ["**/*.ts"]
severity: warning
message: "Console output should be removed"
enabled: true
"#;

    fs::write(rules_dir.join("no_debugger.yaml"), rule1)
        .expect("Failed to write rule 1");
    fs::write(rules_dir.join("no_console.yaml"), rule2)
        .expect("Failed to write rule 2");

    // Initialize rule engine with custom rules
    let mut engine = sentinel_rust::rules::RuleEngine::new()
        .with_project_path(project_path);

    engine.load_custom_rules().expect("Failed to load custom rules");

    // Verify custom rules were loaded
    assert_eq!(
        engine.custom_rules.len(),
        2,
        "Should load both custom rules"
    );
}

