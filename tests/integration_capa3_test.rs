/// Test scenario: Custom rules execution in validation pipeline
#[test]
fn test_capa3_custom_rules_in_validation() {
    let temp_dir = TempDir::new().expect("Failed to create temp dir");
    let project_path = temp_dir.path();

    // Create a custom rule
    let rules_dir = project_path.join(".sentinel").join("custom-rules");
    fs::create_dir_all(&rules_dir).expect("Failed to create rules directory");

    let rule = r#"type: pattern
name: "Test Pattern"
pattern: "FORBIDDEN"
file_patterns: ["**/*.txt"]
severity: error
message: "Found forbidden pattern"
enabled: true
"#;

    fs::write(rules_dir.join("test_rule.yaml"), rule)
        .expect("Failed to write rule");

    // Create rule engine and load custom rules
    let mut engine = sentinel_rust::rules::RuleEngine::new()
        .with_project_path(project_path);

    engine.load_custom_rules().expect("Failed to load custom rules");

    // Validate a file with the custom rule
    let test_file = PathBuf::from("test.txt");
    let content_with_violation = "This file contains FORBIDDEN pattern";
    let content_clean = "This file is clean";

    let violations_bad = engine.validate_file(&test_file, content_with_violation);
    let violations_good = engine.validate_file(&test_file, content_clean);

    assert!(
        violations_bad.iter().any(|v| v.rule_name == "Test Pattern"),
        "Should find custom rule violation"
    );
    assert!(
        !violations_good.iter().any(|v| v.rule_name == "Test Pattern"),
        "Should not find violation in clean code"
    );
}

