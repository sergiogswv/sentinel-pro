/// Test scenario: Capa 3 feature integration
#[test]
fn test_capa3_all_features_together() {
    let temp_dir = TempDir::new().expect("Failed to create temp dir");
    let project_path = temp_dir.path();

    // Initialize git repository
    fs::create_dir_all(project_path.join(".git"))
        .expect("Failed to create .git");

    // Create a Rust project
    fs::write(project_path.join("Cargo.toml"), "[package]\nname=\"test\"\n")
        .expect("Failed to write Cargo.toml");

    let src = project_path.join("src");
    fs::create_dir_all(&src).expect("Failed to create src");
    fs::write(src.join("lib.rs"), "pub fn test() {}")
        .expect("Failed to write lib.rs");

    // Create custom rules
    let rules_dir = project_path.join(".sentinel").join("custom-rules");
    fs::create_dir_all(&rules_dir).expect("Failed to create rules dir");

    let rule = r#"type: pattern
name: "Integration Test Rule"
pattern: "test_pattern"
file_patterns: ["**/*.rs"]
severity: warning
message: "Found test pattern"
enabled: true
"#;

    fs::write(rules_dir.join("integration_test.yaml"), rule)
        .expect("Failed to write custom rule");

    // Verify Rust project detection
    assert!(
        sentinel_rust::config::SentinelConfig::detect_rust_project(project_path),
        "Should detect Rust project"
    );

    // Create and configure rule engine with custom rules
    let mut engine = sentinel_rust::rules::RuleEngine::new()
        .with_project_path(project_path);

    engine.load_custom_rules().expect("Failed to load custom rules");

    // Verify engine has custom rules
    assert!(
        !engine.custom_rules.is_empty(),
        "Should have loaded custom rules"
    );

    // Test validation
    let test_file = PathBuf::from("src/lib.rs");
    let _violations = engine.validate_file(&test_file, "pub fn test_pattern() {}");

    // Test passes if we can load and execute all components
    assert!(true, "All Capa 3 features integrated successfully");
}
