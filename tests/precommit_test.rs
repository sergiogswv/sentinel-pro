//! Integration tests for pre-commit hook functionality

use std::fs;
use tempfile::TempDir;

#[test]
fn test_precommit_template_exists() {
    // The template should be embedded in the binary
    let content = include_str!("../src/precommit_template.sh");
    assert!(!content.is_empty(), "Pre-commit template should not be empty");
}

#[test]
fn test_precommit_template_is_bash_script() {
    let content = include_str!("../src/precommit_template.sh");
    assert!(
        content.starts_with("#!/bin/bash"),
        "Template should be a bash script"
    );
}

